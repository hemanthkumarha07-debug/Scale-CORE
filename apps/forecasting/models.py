import uuid
from decimal import Decimal
from django.db import models
from django.utils.translation import gettext_lazy as _
from apps.core.models import TimeStampedModel
from apps.inventory.models import Product, Warehouse


class ModelType(models.TextChoices):
    LSTM = 'LSTM', _('Deep Learning Multi-Step LSTM')
    XGBOOST = 'XGBOOST', _('Gradient Boosted Trees (XGBoost)')
    EXPONENTIAL_SMOOTHING = 'EXPONENTIAL_SMOOTHING', _('Holt-Winters Exponential Smoothing')
    MOVING_AVERAGE = 'MOVING_AVERAGE', _('Rolling Moving Average')


class ForecastModel(TimeStampedModel):
    """
    Registry of trained demand forecasting models and their benchmark metrics.
    """
    model_name = models.CharField(max_length=100)
    model_type = models.CharField(max_length=50, choices=ModelType.choices, default=ModelType.LSTM)
    version = models.CharField(max_length=30)
    model_file_path = models.CharField(max_length=500, blank=True)
    scaler_file_path = models.CharField(max_length=500, blank=True)
    training_mae = models.DecimalField(max_digits=8, decimal_places=4, null=True, blank=True)
    training_rmse = models.DecimalField(max_digits=8, decimal_places=4, null=True, blank=True)
    training_wape = models.DecimalField(
        max_digits=5,
        decimal_places=4,
        null=True,
        blank=True,
        help_text=_('Weighted Absolute Percentage Error [0.0 - 1.0]. Lower is superior.')
    )
    is_active = models.BooleanField(default=False)
    trained_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        verbose_name = _('Forecast Model')
        verbose_name_plural = _('Forecast Models')
        ordering = ['-trained_at']

    def __str__(self):
        return f"{self.model_name} (v{self.version}) - WAPE: {self.training_wape}"


class DemandForecast(models.Model):
    """
    Persisted multi-step demand predictions generated by the predictive engine.
    """
    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)
    product = models.ForeignKey(Product, on_delete=models.PROTECT, related_name='forecasts')
    warehouse = models.ForeignKey(Warehouse, on_delete=models.PROTECT, related_name='forecasts')
    forecast_date = models.DateField(db_index=True)
    horizon_days = models.PositiveSmallIntegerField(help_text=_('Forecast step horizon (1 to 30 days).'))
    predicted_demand = models.DecimalField(max_digits=12, decimal_places=2)
    confidence_lower = models.DecimalField(max_digits=12, decimal_places=2, null=True, blank=True)
    confidence_upper = models.DecimalField(max_digits=12, decimal_places=2, null=True, blank=True)
    model_used = models.ForeignKey(ForecastModel, on_delete=models.PROTECT, related_name='forecast_records')
    generated_at = models.DateTimeField(auto_now_add=True, db_index=True)

    class Meta:
        verbose_name = _('Demand Forecast')
        verbose_name_plural = _('Demand Forecasts')
        unique_together = ('product', 'warehouse', 'forecast_date', 'horizon_days')
        indexes = [
            models.Index(fields=['product', 'forecast_date']),
            models.Index(fields=['warehouse', 'forecast_date']),
        ]

    def __str__(self):
        return f"{self.product.sku} @ {self.forecast_date} (+{self.horizon_days}d): {self.predicted_demand} units"
